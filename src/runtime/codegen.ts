import type { BehaviorArtifact } from "./contract.js";

/** Typed engine entry points generated from the developer's capability contract. */
export function capabilityBindings(contract: BehaviorArtifact): { csharp: string; typescript: string } {
  const entries = Object.entries(contract.capabilities).sort(([a], [b]) => a.localeCompare(b));
  const name = (key: string) => "cap_" + key.replace(/[^a-zA-Z0-9_]/g, "_");
  if (new Set(entries.map(([key]) => name(key))).size !== entries.length) throw new Error("Capability names collide after code generation");
  const csType = { string: "string", number: "double", boolean: "bool" };
  const cs = [
    "// Generated by WDL. Implement these delegates in your game.",
    "using System; using System.Collections.Generic; using System.Text.Json.Nodes; using System.Threading.Tasks;",
    "namespace Wdl.Generated;",
    "public static class CapabilityBindings {",
    "public static IReadOnlyDictionary<string, Func<JsonObject, Task>> Create(",
    entries.map(([key, schema]) => "Func<" + [...Object.values(schema).map(t => csType[t]), "Task"].join(", ") + "> " + name(key)).join(",\n"),
    ") => new Dictionary<string, Func<JsonObject, Task>> {",
    entries.map(([key, schema]) => "[" + JSON.stringify(key) + "] = args => " + name(key) + "(" +
      Object.entries(schema).map(([field, type]) => "args[" + JSON.stringify(field) + "]!.GetValue<" + csType[type] + ">()").join(", ") + "),").join("\n"),
    "}; }",
  ].join("\n");
  const ts = [
    "// Generated by WDL. Implement this contract in your JS engine.",
    "export type Capabilities = {",
    ...entries.map(([key, schema]) => JSON.stringify(key) + ": (args: { " + Object.entries(schema).map(([field, type]) => JSON.stringify(field) + ": " + type).join("; ") + " }) => void | Promise<void>;"),
    "};",
  ].join("\n");
  return { csharp: cs + "\n", typescript: ts + "\n" };
}
